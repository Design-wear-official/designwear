  void _navigateToTryOn() async {
    showDialog(
      context: context,
      barrierDismissible: false,
      builder: (context) => const Center(
        child: CircularProgressIndicator(color: AppColors.marigold),
      ),
    );
    try {
      final boundary =
          _canvasKey.currentContext?.findRenderObject()
              as RenderRepaintBoundary?;
      if (boundary == null) {
        Navigator.pop(context);
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text('Failed to capture canvas.')),
        );
        return;
      }
      final image = await boundary.toImage(pixelRatio: 2.0);
      final byteData = await image.toByteData(format: ui.ImageByteFormat.png);
      final bytes = byteData?.buffer.asUint8List();
      if (!mounted) return;
      Navigator.pop(context);
      if (bytes != null) {
        Navigator.push(
          context,
          MaterialPageRoute(
            builder: (_) => VirtualTryOnScreen(
              product: Product(
                id: _baseProduct.id,
                title: _design.name.isNotEmpty
                    ? _design.name
                    : _baseProduct.title,
                price: _baseProduct.price,
              ),
              customClothingBytes: bytes,
            ),
          ),
        );
      } else {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text('Failed to export custom design.')),
        );
      }
    } catch (e) {
      if (mounted) {
        Navigator.pop(context);
        ScaffoldMessenger.of(
          context,
        ).showSnackBar(SnackBar(content: Text('Error preparing try-on: $e')));
      }
    }
  }
