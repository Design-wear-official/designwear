extension _ActionMethods on _DesignStudioScreenState {
  static const _autoThemes = [
    'sunrise vibes streetwear',
    'midnight galaxy abstract',
    'wild nature adventure',
    'urban hustle city',
    'summer beach waves',
    'retro 80s neon',
    'minimal zen geometric',
    'hip hop music culture',
  ];

  // ── Load / save ─────────────────────────────────────────────────────────────

  void _loadAutoSavedDesign() async {
    final autoSaved = await _storageService.getAutoSavedDesign();
    if (autoSaved != null && !autoSaved.isEmpty) {
      setState(() {
        _design = autoSaved;
        _historyService.clear();
        _historyService.addToHistory(_design);
      });
    } else {
      WidgetsBinding.instance.addPostFrameCallback((_) {
        if (mounted) _showStarterPicker();
      });
    }
  }

  void _loadCategories() async {
    try {
      final categories = await SanityService().fetchCategories();
      if (!mounted || categories.isEmpty) return;
      setState(() {
        _garmentTypes = categories
            .map((c) {
              final id = c.slug.isNotEmpty ? c.slug : c.id;
              // Fall back to a humanized slug when the CMS title is empty so
              // the chip never renders blank (e.g. "t-shirt" → "T-Shirt").
              final label = c.title.isNotEmpty ? c.title : _humanizeSlug(id);
              return {'id': id, 'label': label};
            })
            .toList();
        if (!_garmentTypes.any((t) => t['id'] == _selectedGarmentType)) {
          _selectedGarmentType = _garmentTypes.first['id']!;
        }
      });
    } catch (_) {}
  }

  /// Turns a slug like "t-shirt" or "tote_bag" into a display label "T-Shirt"
  /// / "Tote Bag". Used as a fallback when a category has no title set.
  String _humanizeSlug(String slug) {
    final words = slug.split(RegExp(r'[\s_]+'));
    String cap(String w) =>
        w.isEmpty ? w : w[0].toUpperCase() + w.substring(1);
    return words
        .map((w) => w.split('-').map(cap).join('-'))
        .join(' ');
  }

  // ── AI generation ───────────────────────────────────────────────────────────

  void _autoGenerateDesign() async {
    setState(() => _isAutoGenerating = true);
    final theme =
        _autoThemes[math.Random().nextInt(_autoThemes.length)];
    final imageBase64 = await _aiService.generateDesignImage(theme);
    if (!mounted) return;
    setState(() => _isAutoGenerating = false);
    if (imageBase64 != null) {
      final imageEl = DesignElement(
        id: DesignStudioUtils.generateElementId(DesignElementType.image),
        type: DesignElementType.image,
        content: imageBase64,
        x: 5,
        y: 10,
        width: DesignStudioConstants.defaultImageSize,
        height: DesignStudioConstants.defaultImageSize,
        side: _side,
      );
      _updateDesign(CustomDesign(name: theme).addElement(imageEl));
    }
  }

  // ── Element CRUD ─────────────────────────────────────────────────────────────

  void _applyTemplate(DesignTemplate template) =>
      _updateDesign(_design.copyWith(elements: template.design.elements));

  void _addTextElement(String text,
      {String? fontFamily, double? fontSize}) {
    final element = DesignElement(
      id: DesignStudioUtils.generateElementId(DesignElementType.text),
      type: DesignElementType.text,
      content: text,
      x: 0,
      y: 0,
      size: fontSize ?? 32,
      properties: {
        'fontFamily': fontFamily ?? 'Outfit',
        'bold': false,
        'italic': false,
        'underline': false,
        'shadow': false,
        'outline': false,
      },
      color: '0xFF15182B',
      side: _side,
    );
    _updateDesign(_design.addElement(element));
    setState(() => _selectedElementId = element.id);
  }

  void _addStickerElement(String emoji) {
    final element = DesignElement(
      id: DesignStudioUtils.generateElementId(DesignElementType.sticker),
      type: DesignElementType.sticker,
      content: emoji,
      x: 0,
      y: 0,
      size: 48,
      side: _side,
    );
    _updateDesign(_design.addElement(element));
    setState(() => _selectedElementId = element.id);
  }

  /// Places an uploaded custom image sticker on the canvas. The bytes are
  /// embedded as base64 (DesignElementType.image) so the existing canvas
  /// rendering and publish-capture pipeline work unchanged.
  void _addImageStickerElement(Uint8List pngBytes) {
    final element = DesignElement(
      id: DesignStudioUtils.generateElementId(DesignElementType.image),
      type: DesignElementType.image,
      content: base64Encode(pngBytes),
      x: 0,
      y: 0,
      width: DesignStudioConstants.defaultImageSize,
      height: DesignStudioConstants.defaultImageSize,
      side: _side,
    );
    _updateDesign(_design.addElement(element));
    setState(() => _selectedElementId = element.id);
  }

  void _addShapeElement(String shape) {
    final element = DesignElement(
      id: DesignStudioUtils.generateElementId(DesignElementType.shape),
      type: DesignElementType.shape,
      content: shape,
      x: 0,
      y: 0,
      width: DesignStudioConstants.defaultShapeSize,
      height: DesignStudioConstants.defaultShapeSize,
      color: '0xFF15182B',
      side: _side,
    );
    _updateDesign(_design.addElement(element));
    setState(() => _selectedElementId = element.id);
  }

  void _duplicateElement(String elementId) {
    final element =
        _design.elements.cast<DesignElement?>().firstWhere(
            (e) => e?.id == elementId,
            orElse: () => null);
    if (element != null) {
      final dup = element.copyWith(
        id: DesignStudioUtils.generateElementId(element.type),
        x: element.x + 20,
        y: element.y + 20,
      );
      _updateDesign(_design.addElement(dup));
      setState(() => _selectedElementId = dup.id);
    }
  }

  void _deleteElement(String elementId) {
    _updateDesign(_design.removeElement(elementId));
    if (_selectedElementId == elementId) {
      setState(() => _selectedElementId = null);
    }
  }

  void _reorderElements(int oldIndex, int newIndex) =>
      _updateDesign(_design.reorderElements(oldIndex, newIndex));

  // ── Selected-element editing helpers ─────────────────────────────────────────

  DesignElement? get _selectedElement => _design.elements
      .cast<DesignElement?>()
      .firstWhere((e) => e?.id == _selectedElementId, orElse: () => null);

  void _nudgeSelected(double dx, double dy) {
    final el = _selectedElement;
    if (el == null) return;
    final nx = (el.x + dx).clamp(
        DesignStudioConstants.printAreaMinX, DesignStudioConstants.printAreaMaxX);
    final ny = (el.y + dy).clamp(
        DesignStudioConstants.printAreaMinY, DesignStudioConstants.printAreaMaxY);
    _updateDesign(_design.updateElement(
        el.id, el.copyWith(x: nx.toDouble(), y: ny.toDouble())));
  }

  /// Live opacity preview while dragging the slider (no history entry).
  void _previewSelectedOpacity(double value) {
    final el = _selectedElement;
    if (el == null) return;
    _previewElement(el.copyWith(opacity: value.clamp(0.0, 1.0)));
  }

  void _toggleFlip(String axis) {
    final el = _selectedElement;
    if (el == null) return;
    final props = Map<String, dynamic>.from(el.properties)
      ..[axis] = !(el.properties[axis] ?? false);
    _updateDesign(
        _design.updateElement(el.id, el.copyWith(properties: props)));
  }

  void _bringForwardSelected() {
    final id = _selectedElementId;
    if (id == null) return;
    final sideElements = _design.elementsForSide(_side);
    final idx = sideElements.indexWhere((e) => e.id == id);
    if (idx >= 0 && idx < sideElements.length - 1) _reorderElements(idx, idx + 1);
  }

  void _sendBackSelected() {
    final id = _selectedElementId;
    if (id == null) return;
    final sideElements = _design.elementsForSide(_side);
    final idx = sideElements.indexWhere((e) => e.id == id);
    if (idx > 0) _reorderElements(idx, idx - 1);
  }

  /// Opens the text editor pre-filled to edit an existing text element.
  void _editElement(String id) {
    final el = _design.elements
        .cast<DesignElement?>()
        .firstWhere((e) => e?.id == id, orElse: () => null);
    if (el == null || el.type != DesignElementType.text) return;
    showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      backgroundColor: Theme.of(context).colorScheme.surface,
      shape: const RoundedRectangleBorder(
        borderRadius: BorderRadius.vertical(top: Radius.circular(24)),
      ),
      builder: (_) => EnhancedTextEditor(
        templateService: _templateService,
        initialText: el.content,
        initialFont: el.properties['fontFamily'] as String? ?? 'Outfit',
        onAddTextElement: (text, font) {
          final props = Map<String, dynamic>.from(el.properties)
            ..['fontFamily'] = font;
          _updateDesign(_design.updateElement(
              id, el.copyWith(content: text, properties: props)));
        },
      ),
    );
  }

  // ── Keyboard shortcuts (desktop / web) ───────────────────────────────────────

  KeyEventResult _handleKey(FocusNode node, KeyEvent event) {
    if (event is KeyUpEvent) return KeyEventResult.ignored;
    final key = event.logicalKey;

    if (key == LogicalKeyboardKey.escape) {
      if (_selectedElementId == null) return KeyEventResult.ignored;
      setState(() => _selectedElementId = null);
      return KeyEventResult.handled;
    }

    final id = _selectedElementId;
    if (id == null) return KeyEventResult.ignored;

    final hw = HardwareKeyboard.instance;
    final ctrl = hw.isControlPressed || hw.isMetaPressed;
    final step = hw.isShiftPressed ? 10.0 : 1.0;

    if (key == LogicalKeyboardKey.arrowLeft) {
      _nudgeSelected(-step, 0);
    } else if (key == LogicalKeyboardKey.arrowRight) {
      _nudgeSelected(step, 0);
    } else if (key == LogicalKeyboardKey.arrowUp) {
      _nudgeSelected(0, -step);
    } else if (key == LogicalKeyboardKey.arrowDown) {
      _nudgeSelected(0, step);
    } else if (key == LogicalKeyboardKey.delete ||
        key == LogicalKeyboardKey.backspace) {
      _deleteElement(id);
    } else if (ctrl && key == LogicalKeyboardKey.keyD) {
      _duplicateElement(id);
    } else if (ctrl && key == LogicalKeyboardKey.bracketRight) {
      _bringForwardSelected();
    } else if (ctrl && key == LogicalKeyboardKey.bracketLeft) {
      _sendBackSelected();
    } else {
      return KeyEventResult.ignored;
    }
    return KeyEventResult.handled;
  }

  void _toggleTextEffect(DesignElement element, String effect) {
    final props = Map<String, dynamic>.from(element.properties)
      ..[effect] = !(element.properties[effect] ?? false);
    _updateDesign(
        _design.updateElement(element.id, element.copyWith(properties: props)));
  }

  void _previewElement(DesignElement updated) =>
      setState(() => _design = _design.updateElement(updated.id, updated));

  void _commitElementChange() {
    _historyService.addToHistory(_design);
    _autoSaveDesign();
  }

  void _onAiDesignUpdate(CustomDesign incoming) {
    final img = incoming.designImageBase64;
    if (img != null && img.isNotEmpty) {
      final imageEl = DesignElement(
        id: DesignStudioUtils.generateElementId(DesignElementType.image),
        type: DesignElementType.image,
        content: img,
        x: 5,
        y: 10,
        width: DesignStudioConstants.defaultImageSize,
        height: DesignStudioConstants.defaultImageSize,
        side: _side,
      );
      _updateDesign(
          incoming.copyWith(designImageBase64: null).addElement(imageEl));
    } else {
      _updateDesign(incoming);
    }
  }

  // ── Canvas capture ──────────────────────────────────────────────────────────

  Future<String?> _captureCanvasPng([GlobalKey? key]) async {
    try {
      final boundary = (key ?? _canvasKey).currentContext?.findRenderObject()
          as RenderRepaintBoundary?;
      if (boundary == null) return null;
      final image = await boundary.toImage(pixelRatio: 2.0);
      final byteData =
          await image.toByteData(format: ui.ImageByteFormat.png);
      final bytes = byteData?.buffer.asUint8List();
      return bytes == null ? null : base64Encode(bytes);
    } catch (_) {
      return null;
    }
  }

  // ── Publish ─────────────────────────────────────────────────────────────────

  Future<void> _publishAndSync() async {
    final authService = Provider.of<AuthService>(context, listen: false);
    final user = authService.currentUser;
    final creatorName = user?.name ?? 'Anonymous';
    final rawHandle = (user?.name ?? 'user')
        .split(' ')
        .first
        .toLowerCase()
        .replaceAll(RegExp(r'[^a-z0-9]'), '');
    final creatorHandle = '@$rawHandle';

    final remixSource = widget.remixSource;
    final newLineage = <Map<String, String>>[
      ...(remixSource?.lineage ?? []),
      if (remixSource != null)
        {
          'handle': remixSource.creatorHandle ?? '',
          'version': remixSource.title,
          'baseColor': remixSource.garmentBaseColor ?? '',
          'artText': remixSource.artText ?? '',
        },
    ];

    final baseColorHex = _design.baseColor.startsWith('0x')
        ? '#${_design.baseColor.substring(4)}'
        : _design.baseColor;

    final textEl = _design.elements
        .where((e) => e.type == DesignElementType.text)
        .firstOrNull;
    final artText =
        (textEl != null && textEl.content.isNotEmpty) ? textEl.content : null;
    final designName =
        _design.name.isNotEmpty ? _design.name : 'Remix by $creatorHandle';

    setState(() => _isPublishing = true);
    // Capture the active (front) canvas first, then the offstage opposite side.
    final frontKey = _side == DesignSide.front ? _canvasKey : _backCanvasKey;
    final backKey  = _side == DesignSide.front ? _backCanvasKey : _canvasKey;
    final previewImage = await _captureCanvasPng(frontKey);
    final backPreviewImage = await _captureCanvasPng(backKey);
    try {
      final apiService = ApiService.webApi(WebApiConfig.baseUrl);
      final productId = await apiService.publishRemix(
        creatorHandle: creatorHandle,
        creatorName: creatorName,
        garmentType: _selectedGarmentType,
        title: designName,
        garmentBaseColor: baseColorHex,
        artText: artText,
        remixedFromId: remixSource?.id,
        remixedFromHandle: remixSource?.creatorHandle,
        remixedFromVersion: remixSource?.title,
        lineage: newLineage,
        tags: remixSource?.tags ?? [],
        designJson: _design.toJson(),
        previewImageBase64: previewImage,
        backPreviewImageBase64: backPreviewImage,
      );

      await _storageService.saveDesign(SavedDesign(
        id: productId,
        name: designName,
        design: _design,
        createdAt: DateTime.now(),
        updatedAt: DateTime.now(),
      ));

      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(const SnackBar(
        content: Text('Design published and synced!'),
        backgroundColor: Color(0xFF2D8B57),
        duration: Duration(seconds: 3),
      ));
      Navigator.pop(context);
    } catch (e) {
      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(SnackBar(
        content: Text('Publish failed: $e'),
        backgroundColor: Colors.red,
        duration: const Duration(seconds: 4),
      ));
    } finally {
      if (mounted) setState(() => _isPublishing = false);
    }
  }

